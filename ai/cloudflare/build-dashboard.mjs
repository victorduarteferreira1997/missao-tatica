// Dependency-free concatenation of this fixed, audited module graph for the dashboard editor.
import { readFile,writeFile } from 'node:fs/promises';
export async function dashboardSource() {
    const paths=['../contract.v1.js','./firebase_auth.mjs','./d1.mjs','./plugin.mjs','./worker.mjs'];
    const sources=await Promise.all(paths.map(p=>readFile(new URL(p,import.meta.url),'utf8')));
    return '// Generated by node ai/cloudflare/build-dashboard.mjs. Do not edit this copy.\n'+sources.map((s,i)=>
        '// '+paths[i]+'\n'+s.replace(/^import .*;\n/gm,'').replace(/^export (?!default)/gm,'')).join('\n');
}
if (process.argv[1] && new URL(import.meta.url).pathname===process.argv[1]) {
    await writeFile(new URL('./worker-dashboard.js',import.meta.url),await dashboardSource());
}
